/**
 * Wrapper for Clooney-Agent — an AI website-cloning agent that screenshots a page at several
 * breakpoints, extracts DOM + computed styles and asks a vision model to inventory its UI components.
 *
 * The repository named in the original spec (saksham-shr/Clooney-Agent) does not exist, so the
 * configured repos are tried in order. The supported implementation is s4sachin/agent-clooney
 * (Gemini vision; `VLMAnalysisAgent.analyzePageVisuals()` → ComponentSpec[]), pinned to a commit.
 * Its analysis is run headlessly through a small runner script with the factory's own `tsx`.
 */

const require = createRequire(import.meta.url);

export interface ClooneyInstall {
  repoUrl: string;
  repoSlug: string;
  dir: string;
  ref: string;
  adapter: "agent-clooney";
}

/** Subset of agent-clooney's ComponentSpec (lib/types/component.ts) that we rely on. */
export interface ClooneyComponentSpec {
  id?: string;
  name?: string;
  category?: string;
  description?: string;
  [k: string]: unknown;
}

const GIT_ENV = {
  GIT_TERMINAL_PROMPT: "0",
  GCM_INTERACTIVE: "never",
  GIT_ASKPASS: "",
  SSH_ASKPASS: "",
};

function repoSlugOf(url: string): string {
  const m = url.match(/github\.com[/:]([^/]+\/[^/.]+)/i);
  return (m ? m[1] : url).toLowerCase();
}

function adapterFor(repoSlug: string): ClooneyInstall["adapter"] | null {
  return /(^|\/)agent-clooney$/i.test(repoSlug) ? "agent-clooney" : null;
}

const RUNNER = `// Generated by artist-site-factory: runs agent-clooney's VLM analysis headlessly.
import { writeFileSync } from "node:fs";
import { createVLMAnalysisAgent } from "../lib/agents/vlm-agent";

const [url, outFile, breakpointsArg] = process.argv.slice(2);
const breakpoints = (breakpointsArg || "mobile,desktop").split(",") as Array<"mobile" | "tablet" | "desktop">;
const agent = createVLMAnalysisAgent();
agent
  .analyzePageVisuals(url, "home", { breakpoints })
  .then((result: any) => {
    writeFileSync(
      outFile,
      JSON.stringify({ components: result.components ?? [], designTokens: result.designTokens ?? null, interactiveElements: result.interactiveElements ?? [], observations: result.observations ?? null }, null, 2),
    );
    process.exit(0);
  })
  .catch((err: unknown) => {
    console.error(err instanceof Error ? err.stack ?? err.message : String(err));
    process.exit(1);
  });
`;

let installPromise: Promise<ClooneyInstall | null> | null = null;

/** Clone (once), pin and install Clooney-Agent into vendor/clooney-agent. Never throws. */
export function ensureClooney(ctx: FactoryContext, logger: Logger): Promise<ClooneyInstall | null> {
  installPromise ??= ensureClooneyImpl(ctx, logger).catch((err: unknown) => {
    logger.warn("Clooney-Agent setup failed", err);
    return null;
  });
  return installPromise;
}

async function ensureClooneyImpl(ctx: FactoryContext, logger: Logger): Promise<ClooneyInstall | null> {
  const cfg = ctx.config.tools.clooney;
  const dir = path.join(ctx.paths.vendorDir, "clooney-agent");
  const marker = path.join(dir, ".factory-installed");
  const runner = path.join(dir, ".factory", "run-analysis.ts");

  if ((await fs.pathExists(marker)) && (await fs.pathExists(runner))) {
    const saved = await readJson<ClooneyInstall>(marker).catch(() => null);
    if (saved?.adapter) return { ...saved, dir };
  }
  if (!(await commandExists("git"))) {
    logger.warn("Clooney-Agent: git is not installed — skipping");
    return null;
  }

  for (const repoUrl of cfg.repoUrls) {
    const repoSlug = repoSlugOf(repoUrl);
    const probe = await run("git", ["-c", "credential.helper=", "ls-remote", "--exit-code", repoUrl, "HEAD"], {
      env: GIT_ENV,
      timeoutMs: 45_000,
      label: "git",
      logger,
      quiet: true,
    });
    if (probe.failed) {
      logger.warn(`Clooney-Agent: repository ${repoUrl} is not available (${probe.timedOut ? "timeout" : "not found"}) — trying the next one`);
      continue;
    }
    const adapter = adapterFor(repoSlug);
    if (!adapter) {
      logger.warn(`Clooney-Agent: no adapter for ${repoSlug} — trying the next repository`);
      continue;
    }
    const ref = cfg.pinnedRefs[repoSlug] ?? "HEAD";
    logger.info(`Clooney-Agent: cloning ${repoUrl} @ ${ref.slice(0, 12)}`);
    await fs.remove(dir);
    await fs.ensureDir(dir);
    const git = (args: string[], timeoutMs = 180_000) =>
      run("git", ["-c", "credential.helper=", ...args], { cwd: dir, env: GIT_ENV, timeoutMs, label: "git", logger });
    const steps: string[][] = [["init", "-q"], ["remote", "add", "origin", repoUrl], ["fetch", "--depth", "1", "origin", ref], ["checkout", "-q", "FETCH_HEAD"]];
    let cloned = true;
    for (const step of steps) {
      const res = await git(step);
      if (res.failed) {
        logger.warn(`Clooney-Agent: git ${step[0]} failed: ${res.all.split("\n").slice(-2).join(" ")}`);
        cloned = false;
        break;
      }
    }
    if (!cloned) continue;
    const sha = (await git(["rev-parse", "HEAD"], 15_000)).stdout.trim();

    logger.info("Clooney-Agent: installing runtime dependencies (one time, a few minutes)");
    const install = await run("npm", ["install", "--omit=dev", "--ignore-scripts", "--no-audit", "--no-fund", "--loglevel=error"], {
      cwd: dir,
      timeoutMs: cfg.installTimeoutMs,
      label: "npm:clooney",
      logger,
    });
    if (install.failed) {
      logger.warn(`Clooney-Agent: npm install failed (exit ${install.exitCode}) — skipping`);
      continue;
    }
    await fs.outputFile(runner, RUNNER, "utf8");
    const result: ClooneyInstall = { repoUrl, repoSlug, dir, ref: sha || ref, adapter };
    await fs.writeJson(marker, result, { spaces: 2 });
    logger.success(`Clooney-Agent ready (${repoSlug} @ ${result.ref.slice(0, 12)})`);
    return result;
  }
  return null;
}

/** Run the VLM component analysis on one URL. Never throws. */
export async function runClooneyAnalysis(
  install: ClooneyInstall,
  opts: {
    url: string;
    outFile: string;
    breakpoints: Array<"mobile" | "tablet" | "desktop">;
    timeoutMs: number;
    geminiApiKey: string;
    logger: Logger;
  },
): Promise<{ ok: boolean; components: ClooneyComponentSpec[]; error?: string }> {
  if (!opts.geminiApiKey) return { ok: false, components: [], error: "GEMINI_API_KEY not set" };
  let tsxCli: string;
  try {
    tsxCli = require.resolve("tsx/cli");
  } catch {
    return { ok: false, components: [], error: "tsx not found" };
  }
  await fs.ensureDir(path.dirname(opts.outFile));
  await fs.remove(opts.outFile);
  const res = await run(process.execPath, [tsxCli, path.join(".factory", "run-analysis.ts"), opts.url, opts.outFile, opts.breakpoints.join(",")], {
    cwd: install.dir,
    env: {
      GOOGLE_GENERATIVE_AI_API_KEY: opts.geminiApiKey,
      OPENAI_API_KEY: process.env.OPENAI_API_KEY,
    },
    timeoutMs: opts.timeoutMs,
    label: "clooney",
    logger: opts.logger,
  });
  if (res.failed || !(await fs.pathExists(opts.outFile))) {
    return { ok: false, components: [], error: res.timedOut ? "timed out" : res.all.split("\n").filter(Boolean).slice(-3).join(" | ") || "analysis failed" };
  }
  try {
    const data = await readJson<{ components?: ClooneyComponentSpec[] }>(opts.outFile);
    return { ok: true, components: Array.isArray(data.components) ? data.components : [] };
  } catch (err) {
    return { ok: false, components: [], error: `unreadable analysis output: ${err instanceof Error ? err.message : String(err)}` };
  }
}

function keywordScore(corpus: string, keywords: string[]): number {
  let score = 0;
  for (const kw of keywords) {
    const k = kw.toLowerCase();
    if (k.length <= 3 ? new RegExp(`(^|[^a-z])${k}([^a-z]|$)`).test(corpus) : corpus.includes(k)) score++;
  }
  return score;
}

/** Map Clooney ComponentSpecs onto our feature types via feature-map keywords (+ category hints). */
export function normalizeClooneyComponents(components: ClooneyComponentSpec[], url: string, featureMap: FeatureMap): Feature[] {
  const out = new Map<string, Feature>();
  for (const c of components) {
    const corpus = `${c.id ?? ""} ${c.name ?? ""} ${c.category ?? ""} ${c.description ?? ""}`.toLowerCase().replace(/[-_]/g, " ");
    let best: { type: string; score: number } | null = null;
    for (const [type, def] of Object.entries(featureMap.featureTypes)) {
      let score = keywordScore(corpus, def.keywords);
      if (c.category === "navigation" && type === "navigation") score += 2;
      if (c.category === "form" && type === "newsletter" && /email|subscribe|newsletter|sign/.test(corpus)) score += 2;
      if (score > 0 && (!best || score > best.score)) best = { type, score };
    }
    if (!best) continue;
    const layout: FeatureLayout = /carousel|slider/.test(corpus)
      ? "carousel"
      : /grid/.test(corpus)
        ? "grid"
        : /full.?width|hero|banner/.test(corpus)
          ? "full-width"
          : /sticky|fixed/.test(corpus)
            ? "sticky"
            : "unknown";
    const existing = out.get(best.type);
    const evidence = `clooney:${c.name ?? c.id ?? "component"}`;
    if (existing) {
      existing.evidence.push(evidence);
      existing.source.confidence = Math.min(1, existing.source.confidence + 0.05);
      continue;
    }
    out.set(best.type, {
      id: `${best.type}-clooney`,
      type: best.type,
      name: String(c.name ?? featureMap.featureTypes[best.type].label),
      description: String(c.description ?? featureMap.featureTypes[best.type].label).slice(0, 400),
      layout,
      components: [slugify(String(c.category ?? "component"), 30)],
      interactions: /button|cta|link/.test(corpus) ? ["cta-click"] : [],
      source: { url, detector: "clooney", confidence: Math.min(0.95, 0.55 + best.score * 0.1) },
      evidence: [evidence],
    });
  }
  return [...out.values()];
}
